import { EGYPTIAN_LEGAL_ARTICLES, CASSATION_RULINGS } from '../data/egyptianLaws.ts';

export interface ConsultationTurn {
  role: 'user' | 'model';
  text: string;
}

export type IntentType =
  | 'INTRO'                // التعريف بالهوية والصفة والمكانة
  | 'SOCIAL'               // سؤال اجتماعي واطمئنان عن الحال
  | 'COLLOQUIAL_CHECKIN'   // أسئلة عامية مصرية للاطمئنان (ايه الدنيا، ايه الاخبار، يا باشا)
  | 'CONFIDENTIAL_PERSONAL'// حديث خاص أو شخصي أو إنساني بعيد عن النزاع القضائي
  | 'CELEBRATION_INVITATION'// أفراح ومناسبات ودعوات اجتماعية (فرح، خطوبة، كتب كتاب، عزومة)
  | 'GREETING'             // تحيات إسلامية أو عامة
  | 'PERMISSION'           // استئذان لطرح سؤال أو فضفضة
  | 'GRATITUDE'            // شكر وامتنان
  | 'DRAFTING'             // طلب صياغة عقود أو محررات
  | 'FOLLOW_UP'            // متابعة واستفسار لاحق
  | 'GENERAL'              // حديث عام أو استفسار فكري/قانوني عام دون نزاع محدد
  | 'MIXED'                // تحية متبوعة باستفسار قانوني
  | 'LEGAL';               // استشارة قانونية موضوعية

/**
 * مصنف النوايا الذكي متعدد الطبقات لمحرك المستشار عطيه الهلباوي
 */
export function detectIntent(message: string, history: ConsultationTurn[] = []): IntentType {
  const q = (message || '').trim().toLowerCase();
  if (!q) return 'GENERAL';

  // كلمات تدل على نزاع أو استشارة قانونية موضوعية
  const legalDisputeKeywords = [
    'عقد', 'بيع', 'شراء', 'شقة', 'إيصال', 'ايصال', 'أمانة', 'امانة', 'شيك', 'محكمة', 'جنحة',
    'جناية', 'دعوى', 'قضية', 'طلاق', 'نفقة', 'ميراث', 'تركة', 'فصل', 'عمل', 'استئناف', 'طعن',
    'نقض', 'إيجار', 'ايجار', 'طرد', 'إخلاء', 'اخلاء', 'محضر', 'شرطة', 'نيابة', 'محامي', 'نصب',
    'تزوير', 'كمبيالة', 'نزاع', 'مستحقات', 'تعويض', 'شفعة', 'تقادم', 'حكم'
  ];
  const hasDispute = legalDisputeKeywords.some((k) => q.includes(k));

  // 1. أفراح ومناسبات ودعوات اجتماعية (CELEBRATION_INVITATION)
  // يغطي: "فرح بنت اختي", "فرحي", "خطوبة", "كتب كتاب", "هتحضر معانا", "معزوم", "عازمك"
  const celebrationKeywords = [
    'فرح', 'عرس', 'زفاف', 'خطوبة', 'خطوبه', 'كتب كتاب', 'سبوع', 'عقيقة', 'تخرج',
    'مناسبة سعيدة', 'مناسبه سعيده', 'هتحضر معانا', 'تيجي تحضر', 'معزوم', 'عازمك', 'تعزمك',
    'عقبال عندكم', 'عقبالك', 'ربنا يفرحك', 'مبروك', 'الف مبروك', 'ألف مبروك'
  ];
  const isCelebration = celebrationKeywords.some((k) => q.includes(k));
  if (isCelebration && !hasDispute) {
    return 'CELEBRATION_INVITATION';
  }

  // 2. حديث خاص / شخصي / إنساني بعيد عن التقاضي (CONFIDENTIAL_PERSONAL)
  const confidentialPersonalKeywords = [
    'حاجه خاصه', 'حاجة خاصة', 'حاجه شخصيه', 'حاجة شخصية', 'موضوع خاص', 'موضوع شخصي',
    'حاجه شخصي', 'حاجة شخصي', 'بعيد عن القانون', 'بعيده عن القانون', 'بعيد عن القوانين',
    'بعيده عن القوانين', 'مش قانوني', 'مش قانون', 'فضفضه', 'فضفضة', 'افضفض', 'أفضفض',
    'احكي معاك في حاجه', 'احكي معاك في موضوع', 'اتكلم معاك في حاجه', 'اتكلم معاك في موضوع',
    'حاجه بيني وبينك', 'حاجة بيني وبينك', 'مش قضيه', 'مش قضية'
  ];
  const isConfidentialPersonal = confidentialPersonalKeywords.some((k) => q.includes(k)) ||
    (q.includes('خاص') && (q.includes('شخص') || q.includes('احكي') || q.includes('اتكلم'))) ||
    (q.includes('شخصي') && (q.includes('بعيد') || q.includes('مش قانون') || q.includes('احكي')));

  if (isConfidentialPersonal && !hasDispute) {
    return 'CONFIDENTIAL_PERSONAL';
  }

  // 2. التحية والاطمئنان بالعامية المصرية (COLLOQUIAL_CHECKIN)
  // يغطي: "ايه الدنيا", "إيه الدنيا", "ايه الاخبار", "إيه الأخبار", "الدنيا عامله ايه", "كله تمام", "يا باشا", "يا غالي", "يا ريس", "يا مستشارنا"
  const colloquialCheckinPatterns = [
    'ايه الدنيا', 'إيه الدنيا', 'الدنيا ايه', 'الدنيا إيه', 'الدنيا عامله ايه', 'الدنيا عاملة إيه',
    'الدنيا عامله إيه', 'الدنيا عاملة ايه', 'الدنيا فيها ايه', 'الدنيا فيها إيه', 'ايه الاخبار',
    'إيه الأخبار', 'اخبارك ايه', 'أخبارك إيه', 'طمني عليك', 'طمنى عليك', 'طمنا عليك', 'طمنا عنك',
    'طمني عنك', 'طمنا', 'طمني', 'كله تمام', 'كله بخير', 'يا باشا', 'يا ريس', 'يا غالي',
    'يا مستشارنا', 'منور يا مستشار', 'منور يا سيادة المستشار', 'عاملين ايه', 'عاملين إيه'
  ];
  const isColloquialCheckin = colloquialCheckinPatterns.some((p) => q === p || q.includes(p));
  if (isColloquialCheckin && !hasDispute) {
    return 'COLLOQUIAL_CHECKIN';
  }

  // 3. التعريف بالهوية والصفة (INTRO / IDENTITY)
  const introPatterns = [
    'عرفني بحضرتك', 'عرفني بنفسك', 'عرفني بيك', 'مين حضرتك', 'من حضرتك', 'من انت', 'من أنت',
    'تقدر تعرفني', 'ممكن تعرفني', 'نبذة عنك', 'معلومات عنك', 'سيرتك الذاتية', 'تاريخك المهني',
    'تخصصك', 'من هو المستشار', 'مين المستشار', 'درجتك العلمية', 'بطاقتك الشخصية', 'احكيلي عنك',
    'احكي لي عنك', 'عرفنا بنفسك', 'عرفنا بحضرتك', 'تشتغل ايه', 'شغلتك ايه'
  ];
  const isIntroQuery = introPatterns.some((p) => q.includes(p)) ||
    (q.includes('تعرفني') && (q.includes('حضرتك') || q.includes('بيك') || q.includes('نفسك')));

  if (isIntroQuery && !hasDispute) {
    return 'INTRO';
  }

  // 4. الشكر والامتنان (GRATITUDE)
  const gratitudePatterns = [
    'شكرا', 'شكراً', 'تسلم', 'جزاك الله', 'كتر خيرك', 'مشكور',
    'الف شكر', 'ألف شكر', 'الله يباركلك', 'تمام فهمت', 'تمام يا مستشار', 'حاضر تمام',
    'تسلم يا غالي', 'تسلم يا مستشار', 'كلك ذوق', 'ونعم بالله', 'ربنا يكرمك'
  ];
  if (gratitudePatterns.some((p) => q === p || q.startsWith(p + ' ') || q.includes(p)) && !hasDispute && !q.includes('بس') && !q.includes('لكن')) {
    return 'GRATITUDE';
  }

  // 5. السؤال الاجتماعي والاطمئنان (SOCIAL)
  const socialPatterns = [
    'عامل ايه', 'عامل إيه', 'اخبارك', 'أخبارك', 'كيفك', 'كيف الحال', 'كيف حالك',
    'ازيك', 'إزيك', 'ازي حضرتك', 'إزي حضرتك', 'صحتك', 'أحوالك', 'احوالك'
  ];
  if (socialPatterns.some((p) => q.includes(p)) && !hasDispute) {
    if (isIntroQuery) return 'INTRO';
    return 'SOCIAL';
  }

  // 6. الاستئذان لطرح سؤال أو فضفضة (PERMISSION)
  const permissionPatterns = [
    'ممكن اسأل', 'ممكن أسأل', 'ممكن سؤال', 'عندي سؤال ممكن', 'ينفع اسأل', 'ينفع أسأل',
    'ممكن استفسار', 'ممكن استشيرك', 'ينفع استشيرك', 'عندي استفسار', 'سؤال لو سمحت',
    'استشارة لو سمحت', 'ممكن اكلمك', 'فاضي اسألك', 'تسمح لي بسؤال', 'ممكن احكي',
    'ممكن اتكلم', 'ممكن اخد رأيك', 'ممكن أخد رأيك', 'عندي موضوع', 'ممكن طلب'
  ];
  if (permissionPatterns.some((p) => q.includes(p)) && !hasDispute) {
    return 'PERMISSION';
  }

  // 7. التحيات (GREETINGS)
  const greetingPatterns = [
    'السلام عليكم', 'سلام عليكم', 'صباح الخير', 'مساء الخير', 'أهلا', 'اهلا',
    'مرحبا', 'مرحب', 'تحياتي', 'نهارك سعيد', 'يا هلا'
  ];
  const hasGreeting = greetingPatterns.some((p) => q.includes(p));

  if (hasGreeting) {
    if (isIntroQuery) return 'INTRO';
    if (hasDispute || q.length > 50) return 'MIXED';
    return 'GREETING';
  }

  // 8. طلبات الصياغة (DRAFTING)
  const draftingKeywords = [
    'صيغة عقد', 'نموذج عقد', 'عايز عقد', 'مطلوب صيغة', 'اكتبلي عقد', 'اكتب لي عقد',
    'صيغة ايصال', 'صيغة إيصال', 'صيغة انذار', 'صيغة إنذار', 'صيغة توكيل', 'صيغة اقرار',
    'صيغة إقرار', 'صيغة دعوى', 'صيغة مذكرة', 'مسودة عقد', 'صياغة عقد', 'نموذج اتفاق'
  ];
  if (draftingKeywords.some((k) => q.includes(k))) {
    return 'DRAFTING';
  }

  // 9. أسئلة المتابعة السياقية (FOLLOW_UP)
  const followUpStarters = [
    'وماذا لو', 'ماذا لو', 'طب لو', 'طب ولو', 'طب وإذا', 'طب واذا', 'وإذا', 'واذا',
    'وان امتنع', 'وإن امتنع', 'وما الحكم', 'وبالنسبة', 'طب ايه الحل', 'طب إيه الحل',
    'لو رفض', 'طب بعد كدة', 'طب وبعدين'
  ];
  if (followUpStarters.some((s) => q.startsWith(s) || q.includes(s)) && history.length > 0) {
    return 'FOLLOW_UP';
  }

  // 10. استشارة قانونية موضوعية
  if (hasDispute) {
    return 'LEGAL';
  }

  // 11. حوار معرفي عام
  return 'GENERAL';
}

