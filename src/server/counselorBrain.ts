/**
 * استخراج أطراف العقد وبياناته من نص الطلب
 */
export interface ExtractedContractEntities {
  contractType: string;
  seller?: string;
  buyer?: string;
  propertyType?: string;
  price?: string;
  location?: string;
  hasSufficientData: boolean;
  missingItems: string[];
}

export function extractContractEntities(text: string): ExtractedContractEntities {
  // تنظيف النص وتوحيد الفواصل
  const normalized = (text || '')
    .replace(/[«»""''():]/g, ' ')
    .replace(/[،,؛;\n]+/g, ' ، ');

  // استخراج البائع
  let seller: string | undefined;
  const sellerMatch = normalized.match(
    /(?:البائع|طرف\s*أول|الطرف\s*الأول|بائع)\s*(?:هو|السيد)?\s*([^\n،,؛.]+?)(?=\s*[،,؛]?\s*(?:والمشتري|والمشترى|المشتري|المشترى|طرف\s*ثان|الطرف\s*الثاني|مقابل|بثمن|نظير|$))/i
  );
  if (sellerMatch && sellerMatch[1]) {
    const s = sellerMatch[1].trim();
    if (s.length > 2 && !s.includes('عقد') && !s.includes('شقة')) {
      seller = s;
    }
  }

  // استخراج المشتري
  let buyer: string | undefined;
  const buyerMatch = normalized.match(
    /(?:المشتري|المشترى|طرف\s*ثان|طرف\s*ثاني|الطرف\s*الثاني|مشتري|مشترى)\s*(?:هو|السيد)?\s*([^\n،,؛.]+?)(?=\s*[،,؛]?\s*(?:والبائع|البائع|مقابل|بثمن|نظير|والشقة|والعقار|$))/i
  );
  if (buyerMatch && buyerMatch[1]) {
    const b = buyerMatch[1].trim();
    if (b.length > 2 && !b.includes('عقد') && !b.includes('شقة')) {
      buyer = b;
    }
  }

  const clean = normalized.replace(/[،,؛]/g, ' ');

  // نوع العقد والعين
  let propertyType = 'وحدة سكنية (شقة)';
  if (clean.includes('أرض') || clean.includes('ارض') || clean.includes('قطعة')) propertyType = 'قطعة أرض فضاء';
  else if (clean.includes('محل') || clean.includes('تجاري')) propertyType = 'محل تجاري';
  else if (clean.includes('عقار') || clean.includes('عمارة') || clean.includes('بيت')) propertyType = 'عقار كامل';
  else if (clean.includes('سيارة') || clean.includes('مركبة')) propertyType = 'سيارة ملاكي';

  // تحديد ما ينقص من معلومات جوهرية
  const missingItems: string[] = [];

  if (!clean.includes('شارع') && !clean.includes('منطقة') && !clean.includes('محافظة') && !clean.includes('مدينة') && !clean.includes('كائن')) {
    missingItems.push('بيانات الوحدة وموقعها الدقيق (رقم الشقة، الدور، اسم العقار، العنوان التفصيلي، والحدود الأربعة)');
  }
  if (!clean.includes('متر') && !clean.includes('مساحة')) {
    missingItems.push('المساحة الإجمالية والصافية بالمتر المربع ونسبة الحصة الشائعة في الأرض والأجزاء المشتركة');
  }
  if (!clean.includes('جنيه') && !clean.includes('ج.م') && !clean.includes('مبلغ') && !clean.includes('ألف') && !clean.includes('مليون') && !/\d{4,}/.test(clean)) {
    missingItems.push('الثمن الإجمالي المتفق عليه، ومقدار الدفعة المقدمة عند التوقيع، وجدول الأقساط المتبقية إن وجدت');
  }
  if (!clean.includes('تسليم') && !clean.includes('استلام')) {
    missingItems.push('موعد التسليم الفعلي للحيازة وحالة الشقة (تشطيب كامل/نصف تشطيب)');
  }
  if (!clean.includes('سند') && !clean.includes('مشهر') && !clean.includes('مسجل') && !clean.includes('ميراث') && !clean.includes('ملكية')) {
    missingItems.push('سند ملكية البائع وأيلولة العقار (عقد بيع مسجل، حكم صحة ونفاذ، أو إعلام وراثة رسمي)');
  }

  const hasSufficientData = !!(seller && buyer && missingItems.length <= 1);

  return {
    contractType: `عقد بيع ابتدائي لـ ${propertyType}`,
    seller,
    buyer,
    propertyType,
    hasSufficientData,
    missingItems,
  };
}

/**
 * فحص الأسئلة غير المكتملة أو الغامضة التي تحتاج لاستيضاح ذكي
 */
function isAmbiguousLegalClaim(q: string): boolean {
  const shortQueries = [
    'عايز أرفع دعوى تعويض', 'عايز ارفع دعوى تعويض', 'عايز ارفع قضية تعويض', 'ارفع دعوى تعويض ازاي',
    'عاوز تعويض', 'عايز تعويض', 'ارفع قضية تعويض ازاي', 'كيف ارفع دعوى تعويض',
    'عايز ارفع قضية', 'عايز ارفع دعوى', 'عايز اشتكي', 'ارفع قضية ازاي', 'ازاي اخد حقي'
  ];
  return shortQueries.some((sq) => q === sq || (q.startsWith(sq) && q.length < 45));
}

/**
 * فحص طلبات المواد أو الأحكام الوهمية (Zero Hallucination check)
 */
function isHallucinationTrap(q: string): boolean {
  // مواد غير موجودة بقانون العقوبات المصري (قانون العقوبات المصري ينتهي بالمادة 395)
  if (q.includes('عقوبات') && (q.includes('999') || q.includes('888') || q.includes('777') || q.includes('600') || q.includes('500') || q.includes('450') || q.includes('400'))) {
    return true;
  }
  // طعون خيالية بأرقام غير منطقية
  if (q.includes('999999') || q.includes('111111') || q.includes('888888') || (q.includes('طعن') && q.includes('99999'))) {
    return true;
  }
  return false;
}

